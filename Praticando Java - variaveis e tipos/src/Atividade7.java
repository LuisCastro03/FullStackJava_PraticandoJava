//Atividade 7 - Par ou ímpar?

public class Atividade7 {
    public static void main(String[] args) {
        System.out.println("Hello, world!");

        System.out.println();

        int numero = 7;

        if (numero % 2 == 0) {
            System.out.println("O número é par.");
        } else {
            System.out.println("O número é ímpar.");
        }
    }
}

